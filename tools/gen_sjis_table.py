# gen_sjis_table.py - generate src/os/posix/sjis_table.c
#
# The POSIX back end converts CP932 (Shift-JIS) through iconv
# (src/os/posix/sjis.c).  bionic only has iconv from API 28 on and its
# CP932 alias is not guaranteed, so Android uses a built-in table instead;
# a desktop build can select it with SJIS_TABLE=1 to test it.
#
# The table comes from Python's cp932 codec, i.e. the Microsoft code page
# 932 the engine was written for.  Run this script from the repository
# root and commit the result:
#
#     python3 tools/gen_sjis_table.py
#
# Both directions are generated:
#   SjisTable_ToUnicode(code)       two-byte code (0x8140 ...) -> code point,
#                                   U+FFFD when CP932 has no such code
#   SjisTable_FromUnicode(cp, out)  code point -> 1 or 2 bytes, 0 when CP932
#                                   has no such code
#
# The result is a C file with sparse designated initialisers, so only the
# assigned entries appear in the source; the compiler fills the rest with
# zero (the "not mapped" value).

import sys

OUT = "src/os/posix/sjis_table.c"

# the leads that start a two-byte code: 0x81-0x9F (JIS X 0208) and
# 0xE0-0xFC (the NEC/IBM extensions); 0x40-0x7E and 0x80-0xFC are trails
# (0x7F is not used)
LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = list(range(0x40, 0x7F)) + list(range(0x80, 0xFD))

# glibc's CP932 differs from the Microsoft code page on these seven
# two-byte codes (the classic wave dash / backslash set).  The table follows
# glibc so that a SJIS_TABLE=1 desktop build converts exactly like the
# iconv build; the fullwidth code points they replace are then not
# encodable, exactly as they are not with iconv.
GLIBC_PARITY = {
    0x815F: 0x005C,  # reverse solidus (Microsoft: U+FF3C)
    0x8160: 0x301C,  # wave dash (Microsoft: U+FF5E)
    0x8161: 0x2016,  # double vertical line (Microsoft: U+2225)
    0x817C: 0x2212,  # minus sign (Microsoft: U+FF0D)
    0x8191: 0x00A2,  # cent sign (Microsoft: U+FFE0)
    0x8192: 0x00A3,  # pound sign (Microsoft: U+FFE1)
    0x81CA: 0x00AC,  # not sign (Microsoft: U+FFE2)
}

# glibc's CP932 also encodes the two JIS X 0201 characters to the ASCII
# bytes the decoder shows as U+005C and U+007E; the table follows it so that
# the two directions stay as they are with iconv
GLIBC_EXTRA = {
    0x00A5: 0x005C,  # yen sign
    0x203E: 0x007E,  # overline
}


def build():
    to_unicode = {}
    for lead in LEADS:
        for trail in TRAILS:
            code = (lead << 8) | trail
            try:
                s = bytes((lead, trail)).decode("cp932")
            except UnicodeDecodeError:
                continue
            if len(s) != 1 or ord(s) >= 0x10000:
                raise SystemExit("unexpected CP932 decoding of %04X: %r" % (code, s))
            to_unicode[code] = ord(s)

    dropped = set()  # the Microsoft code points the parity overrides replace
    for code, cp in GLIBC_PARITY.items():
        old = to_unicode.get(code)
        if old is not None and old != cp:
            dropped.add(old)
        to_unicode[code] = cp

    from_unicode = {}
    for cp in range(0x10000):
        if 0xD800 <= cp <= 0xDFFF or cp in dropped:
            continue
        try:
            b = chr(cp).encode("cp932")
        except UnicodeEncodeError:
            continue
        if len(b) == 1:
            from_unicode[cp] = b[0]
        elif len(b) == 2:
            from_unicode[cp] = (b[0] << 8) | b[1]
        else:
            raise SystemExit("unexpected CP932 encoding of U+%04X: %r" % (cp, b))

    for code, cp in GLIBC_PARITY.items():
        if cp >= 0x80:  # U+005C is plain ASCII and stays a single byte
            from_unicode[cp] = code

    from_unicode.update(GLIBC_EXTRA)

    return to_unicode, from_unicode


def emit(f, name, table, comment):
    f.write("// %s\n" % comment)
    f.write("static const uint16_t %s[0x10000] = {\n" % name)
    items = sorted(table.items())
    line = "\t"
    for i, (k, v) in enumerate(items):
        item = "[0x%04x] = 0x%04x," % (k, v)
        if len(line) + len(item) > 100:
            f.write(line.rstrip() + "\n")
            line = "\t"
        line += item + " "
    if line.strip():
        f.write(line.rstrip() + "\n")
    f.write("};\n\n")


def main():
    to_unicode, from_unicode = build()
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("""/*
 * This file is part of OpenBGI (https://openbgi.net).
 * SPDX-License-Identifier: GPL-2.0-only
 *
 * sjis_table.c - the CP932 tables of src/os/posix/sjis.c for builds without
 *                iconv (Android) and for a desktop build with SJIS_TABLE=1
 *
 * GENERATED by tools/gen_sjis_table.py from Python's cp932 codec (the
 * Microsoft code page 932 the engine was written for); do not edit.
 *
 *   SjisTable_ToUnicode       two-byte Shift-JIS code -> code point,
 *                             U+FFFD when CP932 has no such code
 *   SjisTable_FromUnicode     code point -> 1 or 2 Shift-JIS bytes, 0 when
 *                             CP932 has no such code
 */
#include <stdint.h>

""")
        emit(f, "gSjisTableToUnicode", to_unicode,
             "two-byte Shift-JIS code (0x8140 ...) -> Unicode; 0 = not in CP932")
        emit(f, "gSjisTableFromUnicode", from_unicode,
             "Unicode -> Shift-JIS: 0 = not in CP932, <= 0xFF one byte, else two bytes big-endian")
        f.write("""uint32_t SjisTable_ToUnicode(uint16_t code)
{
	return gSjisTableToUnicode[code] ? gSjisTableToUnicode[code] : 0xfffd;
}

// 1 or 2 bytes in `out`, 0 when CP932 has no code for the code point
// (the caller turns that into '?', as it does when iconv refuses)
int SjisTable_FromUnicode(uint32_t cp, char out[2])
{
	uint16_t code;
	if(cp >= 0x10000)
		return 0;
	code = gSjisTableFromUnicode[cp];
	if(!code)
		return 0;
	if(code <= 0xff) // halfwidth katakana
	{
		out[0] = (char)code;
		return 1;
	}
	out[0] = (char)(code >> 8);
	out[1] = (char)code;
	return 2;
}
""")
    print("%s: %d two-byte codes, %d code points" % (OUT, len(to_unicode), len(from_unicode)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
